#!/usr/bin/env bash
# Regenerate room-server/vendor/room-worker.ts: the exact Cloudflare room Worker
# (pinned Arcana source + Chimera's directed-room patch) that the self-hosted
# Node room server runs. One protocol, one implementation, two hosts.
#   scripts/sync_room_server_worker.sh          rewrite the vendored file
#   scripts/sync_room_server_worker.sh --check  fail if it is out of date
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ARCANA_WORKER_SHA="${ARCANA_WORKER_SHA:-a5c428ad3da42b7325adf6630238ec992fee3113}"
OUT="$ROOT/room-server/vendor/room-worker.ts"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
git clone --quiet --filter=blob:none --no-checkout https://github.com/AARMOU/arcana_table.git "$TMP/arcana"
git -C "$TMP/arcana" checkout --quiet "$ARCANA_WORKER_SHA" -- android/cloud-room/src/index.ts android/cloud-room/scripts/verify-directed-relay.mjs
cp "$TMP/arcana/android/cloud-room/src/index.ts" "$TMP/index.ts"
python3 "$ROOT/scripts/patch_directed_room_resumption.py" "$TMP/index.ts" > /dev/null
{
  echo "// GENERATED by scripts/sync_room_server_worker.sh — do not edit by hand."
  echo "// Source: AARMOU/arcana_table@$ARCANA_WORKER_SHA android/cloud-room/src/index.ts"
  echo "// plus scripts/patch_directed_room_resumption.py. GPL-3.0 (see repository licence)."
  cat "$TMP/index.ts"
} > "$TMP/room-worker.ts"
TEST_OUT="$ROOT/room-server/test/vendor-verify-directed-relay.mjs"
{
  echo "// GENERATED by scripts/sync_room_server_worker.sh from AARMOU/arcana_table@$ARCANA_WORKER_SHA"
  echo "// android/cloud-room/scripts/verify-directed-relay.mjs — do not edit by hand."
  cat "$TMP/arcana/android/cloud-room/scripts/verify-directed-relay.mjs"
} > "$TMP/verify.mjs"
if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "$TMP/verify.mjs" "$TEST_OUT"; then
    echo "::error::room-server/test/vendor-verify-directed-relay.mjs is out of date. Run scripts/sync_room_server_worker.sh" >&2
    exit 1
  fi
  if ! cmp -s "$TMP/room-worker.ts" "$OUT"; then
    echo "::error::room-server/vendor/room-worker.ts is out of date. Run scripts/sync_room_server_worker.sh" >&2
    diff -u "$OUT" "$TMP/room-worker.ts" | head -60 >&2 || true
    exit 1
  fi
  echo "room-server/vendor/room-worker.ts matches the pinned Worker + patch."
else
  mkdir -p "$(dirname "$TEST_OUT")"
  cp "$TMP/room-worker.ts" "$OUT"
  cp "$TMP/verify.mjs" "$TEST_OUT"
  echo "Wrote $OUT and $TEST_OUT"
fi
